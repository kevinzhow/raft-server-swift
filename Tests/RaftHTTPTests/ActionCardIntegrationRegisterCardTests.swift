/// The integration card preparer, the `#channel` target resolver and the
/// thread-carrier lookups the retired `ActionCardDirectoryHelpers` owned.

private struct Appended: Sendable {
    var messageId: String
    var channelId: String
    var content: String
    var cardExistedAtAppend: Bool
}

private final class Log: Sendable {
    private let storage = Mutex<[Appended]>([])
    var rows: [Appended] { storage.withLock { $0 } }
    func append(_ row: Appended) -> Int {
        storage.withLock { rows in
            rows.append(row)
            return rows.count
        }
    }
}

private func makeService(
    directory: EmailLoginDirectory,
    appended: Log
) -> ActionCardIntegrationRegisterService {
    let cards = directory.managedMCPAndCardsStore
    return ActionCardIntegrationRegisterService(
        cards: cards,
        channels: directory.serversAndChannelsStore,
        messages: directory.messagesAndThreadsStore,
        inboxFacts: directory.inboxFactStore,
        accounts: directory.authProfileStore,
        agents: directory.agentsRuntimeStore,
        oauth: directory.oauth,
        dependencies: ActionCardIntegrationRegisterDependencies(
            sessionUserId: { _ in nil },
            agentCredential: { _ in nil },
            identityResolution: { _, _ in .missingAuthorization },
            appendHumanMessage: { message in
                let existed = cards.integrationRegisterCard(messageId: message.id) != nil
                return appended.append(Appended(
                    messageId: message.id,
                    channelId: message.channelId,
                    content: message.content,
                    cardExistedAtAppend: existed
                ))
            },
            addPostableChannel: { _, _, _, _, _, _, _ in },
            emitRealtime: { _, _, _ in },
            marketplaceInstallableClient: { _ in nil },
            publicIntegrationClient: { _ in nil }
        )
    )
}

private func agent(_ id: String, display: String = "") -> OAuthLedger.AgentRuntimeInfo {
    OAuthLedger.AgentRuntimeInfo(
        id: id, serverId: "srv", name: "bot-\(id)", displayName: display, description: nil,
        avatarUrl: nil, creatorUserId: nil, runtime: "claude", runtimeConfigJSON: nil,
        envVarsJSON: nil, status: "active", deleted: false
    )
}

@Test func preparedCardStoresTheCardBeforeTheCarrierMessageAppears() throws {
    let directory = EmailLoginDirectory()
    let appended = Log()
    let service = makeService(directory: directory, appended: appended)
    let messageId = service.prepareIntegrationRegisterCard(
        serverId: "srv", agent: agent("a1", display: "Display"), name: "App", clientKey: "ck",
        homepageUrl: nil, returnUrl: "https://x.example/cb", agentManifestUrl: nil,
        setupUrl: nil, setupDescription: nil, scopes: ["openid"], target: (local: "loc", storage: "sto")
    )
    let row = try #require(appended.rows.first)
    #expect(row.messageId == messageId)
    #expect(row.channelId == "sto")
    #expect(row.content == "Operation: register Login with Raft app App (ck)")
    #expect(row.cardExistedAtAppend)
    let card = try #require(directory.managedMCPAndCardsStore.integrationRegisterCard(messageId: messageId))
    #expect(card.agentName == "Display")
    #expect(card.storageChannelId == "sto")
    #expect(card.localCarrierChannelId == "loc")
    #expect(card.state == "prepared")
    #expect(messageId == messageId.lowercased())
}

