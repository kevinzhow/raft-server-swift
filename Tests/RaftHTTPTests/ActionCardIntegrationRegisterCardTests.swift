}

@Test func concurrentPreparesNeverExposeACarrierWithoutItsCard() async {
    let directory = EmailLoginDirectory()
    let appended = Log()
    let service = makeService(directory: directory, appended: appended)
    let ids = await withTaskGroup(of: String.self) { group in
        for index in 0..<48 {
            group.addTask {
                service.prepareIntegrationRegisterCard(
                    serverId: "srv", agent: agent("a\(index)"), name: "App\(index)", clientKey: nil,
                    homepageUrl: nil, returnUrl: "r", agentManifestUrl: nil, setupUrl: nil,
                    setupDescription: nil, scopes: [], target: (local: "l", storage: "s")
                )
            }
        }
        var all: [String] = []
        for await id in group { all.append(id) }
        return all
    }
    #expect(Set(ids).count == 48)
    let rows = appended.rows
    #expect(rows.count == 48)
    #expect(rows.allSatisfy { $0.cardExistedAtAppend })
    #expect(directory.managedMCPAndCardsStore.state.integrationRegisterCards.count == 48)
}

private func seedChannels(_ directory: EmailLoginDirectory) {
    let store = directory.serversAndChannelsStore
    store.postableChannels["pub"] = PostableChannel(serverId: "srv", memberIds: [], kind: "channel", name: "general")
    store.postableChannels["priv"] = PostableChannel(serverId: "srv", memberIds: ["member"], kind: "private", name: "secret")
    store.postableChannels["gone"] = PostableChannel(serverId: "srv", memberIds: [], kind: "channel", deletedAt: Date(), name: "old")
    store.postableChannels["other"] = PostableChannel(serverId: "srv-2", memberIds: [], kind: "channel", name: "general")
    store.postableChannels["jointlocal"] = PostableChannel(serverId: "srv", memberIds: ["member"], kind: "joint", name: "shared")
    store.jointProjections = [JointChannelLink(localChannelId: "jointlocal", canonicalChannelId: "canon", serverId: "srv")]
}

@Test func targetResolutionKeepsTheLegacyVisibilityRules() {
    let directory = EmailLoginDirectory()
    seedChannels(directory)
    let service = makeService(directory: directory, appended: Log())
    func resolve(_ agentId: String, _ target: String) -> String? {
        service.actionCardTarget(serverId: "srv", agentId: agentId, target: target).map { "\($0.local)>\($0.storage)" }
    }
    #expect(resolve("anyone", "#general") == "pub>pub")
    #expect(resolve("anyone", "general") == nil)
    #expect(resolve("anyone", "#old") == nil)
    #expect(resolve("anyone", "#missing") == nil)
    #expect(resolve("anyone", "#secret") == nil)
    #expect(resolve("member", "#secret") == "priv>priv")
    #expect(resolve("member", "#shared") == "jointlocal>canon")
    #expect(resolve("stranger", "#shared") == nil)
}

@Test func historyThreadLookupsMatchTheRetiredDirectoryHelpers() {
    let directory = EmailLoginDirectory()
    let store = directory.serversAndChannelsStore
    store.postableChannels["abcdef-thread"] = PostableChannel(
        serverId: "srv", memberIds: [], kind: "thread", parentChannelId: "parent", parentMessageId: "msg-12345", name: "t"
    )
    store.postableChannels["deleted-thread"] = PostableChannel(
        serverId: "srv", memberIds: [], kind: "thread", parentChannelId: "parent", parentMessageId: "msg-9", deletedAt: Date(), name: "t"
    )
    store.postableChannels["abc-channel"] = PostableChannel(serverId: "srv", memberIds: [], kind: "channel", name: "c")
    #expect(store.historyThread(parentId: "parent", anchorMessageId: "msg-12345") == "abcdef-thread")
    #expect(store.historyThread(parentId: "parent", anchorMessageId: "msg-1234") == nil)
    #expect(store.historyThread(parentId: "other", anchorMessageId: "msg-12345") == nil)
    #expect(store.historyThread(parentId: "parent", anchorMessageId: "msg-9") == nil)
    #expect(store.historyThread(parentId: "parent", idPrefix: "abc") == "abcdef-thread")
    #expect(store.historyThread(parentId: "parent", idPrefix: "zzz") == nil)
    #expect(store.historyThread(parentId: "parent", idPrefix: "deleted") == nil)
    #expect(store.historyThread(parentId: "parent", anchorPrefix: "msg-12") == "abcdef-thread")
    #expect(store.historyThread(parentId: "parent", anchorPrefix: "msg-9") == nil)
    #expect(store.historyThread(parentId: "parent", anchorPrefix: "nope") == nil)
}
