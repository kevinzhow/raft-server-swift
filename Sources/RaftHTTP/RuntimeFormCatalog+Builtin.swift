    static func builtinV2ProviderSource(schemaVersion: String, supportedModelIDs: Set<String>? = nil) -> OrderedJSON {
        let providers = builtinV2ProviderNames.filter { provider in
            builtinGatewayIDs.contains(provider.id) || (supportedModelIDs.map { ids in ids.contains { $0.hasPrefix(provider.id + "/") } } ?? true)
        }
        return .object([
            .init("protocolVersion", 1), .init("runtimeId", "builtin"), .init("schemaVersion", schemaVersion),
            .init("sourceId", "provider"), .init("kind", "select"), .init("pointer", "/providerId"),
            .init("options", .array(providers.map { provider in .object([
                .init("value", provider.id), .init("label", provider.label),
                .init("providerKind", builtinGatewayIDs.contains(provider.id) ? "gateway" : "preset"),
            ]) })),
            .init("defaultValue", providers.contains { $0.id == "deepseek" } ? "deepseek" : providers.first?.id ?? ""),
        ])
    }

    static func builtinV2Definition(schemaVersion: String, chinese: Bool, values: JSONValue? = nil) -> OrderedJSON {
        // Typed immutable schema data mirrors the released Node fixture.
        // Copy-on-write edits leave the frozen V1 definition unchanged.
        var body = builtinV2English
        body["schemaVersion"] = .string(schemaVersion)
        if case .object(var refs)? = body["optionSources"] {
            for key in Array(refs.keys) {
                if case .object(var ref)? = refs[key] { ref["schemaVersion"] = .string(schemaVersion); refs[key] = .object(ref) }
            }
            body["optionSources"] = .object(refs)
        }
        if chinese, case .object(var ui)? = body["uiSchema"], case .object(var copy)? = ui["localization"] {
            for key in Array(copy.keys) {
                guard case .object(var field)? = copy[key] else { continue }
                for part in ["label", "hint", "placeholder"] {
                    if case .string(let text)? = field[part], let translated = builtinChineseCopy[text] { field[part] = .string(translated) }
                }
                copy[key] = .object(field)
            }
            ui["localization"] = .object(copy); body["uiSchema"] = .object(ui)
        }
        if let values {
            body["values"] = values
            body["writeOnlyKeepRequiresUnchanged"] = .object(["/apiKey": .array([.string("/providerId"), .string("/baseUrl")])])
        }
        return .raw(try! JSONValue.object(body).string())
    }

